export interface Room {
  slug: string;
  title: string;
  people: number;
  images: string[];
  price: string;
  shortDescription: string;
  cardDescription: string;
  description: string;
  roomInfo: RoomInfo[];
  features: {
    inRoom: string[];
    bathroom: string[];
  };
  seo: {
    title: string;
    description: string;
    keywords: string;
    ogTitle: string;
    ogDescription: string;
    ogImage: string;
  };
  schema?: object;
}

interface RoomInfo {
  label: string;
  value: string;
}

const SITE_URL = "https://troy-hotel.ru";
const HOTEL_NAME = "Парк-отель «Троя»";

const buildAssetUrl = (folder: string, file: string) =>
  `${SITE_URL}/new_photo/${encodeURIComponent(folder)}/${encodeURIComponent(
    file
  )}`;

const toSchemaAmenities = (features: string[]) =>
  features.map((name) => ({
    "@type": "LocationFeatureSpecification",
    name,
    value: true,
  }));

const buildRoomSeo = ({
  title,
  description,
  keywords,
  ogTitle,
  ogDescription,
  image,
}: {
  title: string;
  description: string;
  keywords: string;
  ogTitle: string;
  ogDescription: string;
  image: string;
}) => ({
  title: `${title} — ${HOTEL_NAME} в Краснодаре`,
  description,
  keywords,
  ogTitle,
  ogDescription,
  ogImage: image,
});

const buildRoomSchema = ({
  title,
  description,
  image,
  price,
  amenities,
  area,
  guests,
  slug,
}: {
  title: string;
  description: string;
  image: string;
  price: string;
  amenities: string[];
  area: number;
  guests: number;
  slug: string;
}) => ({
  "@context": "https://schema.org",
  "@type": "LodgingBusiness",
  name: `${title} — ${HOTEL_NAME}`,
  description,
  image,
  priceRange: `${price} RUB`,
  amenityFeature: toSchemaAmenities(amenities),
  floorSize: {
    "@type": "QuantitativeValue",
    value: area,
    unitCode: "MTK",
  },
  occupancy: {
    "@type": "QuantitativeValue",
    maxValue: guests,
  },
  offers: {
    "@type": "Offer",
    price: Number(price),
    priceCurrency: "RUB",
    availability: "https://schema.org/InStock",
    url: `${SITE_URL}/rooms/${slug}`,
  },
});

